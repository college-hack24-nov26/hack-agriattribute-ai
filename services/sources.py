def counts(items: List[Dict[str, str]]) -> Dict[str, int]:
    c = {LIVE: 0, SNAPSHOT: 0, SIMULATED: 0, OFF: 0}
    for i in items:
        c[i["state"]] = c.get(i["state"], 0) + 1
    return c


def has_gemini_key() -> bool:
    return bool(os.getenv("GEMINI_API_KEY"))
