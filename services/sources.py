"""
sources.py - one honest list of where the app's numbers come from.

Every external source is reported in the same shape so the interface can show a "trust strip":

    {"name": ..., "role": ..., "state": LIVE | SNAPSHOT | SIMULATED | OFF, "detail": ...}

  LIVE       fetched from the provider just now (or within the cache window)
  SNAPSHOT   real reference data that is not live (a file, a regional average, a cached copy)
  SIMULATED  generated by us for the demo; never to be read as a measurement
  OFF        not configured, the app falls back to something simpler
"""

import os
from typing import Any, Dict, List, Optional

LIVE, SNAPSHOT, SIMULATED, OFF = "LIVE", "SNAPSHOT", "SIMULATED", "OFF"

STATE_STYLE = {
    LIVE: ("#065f46", "#d1fae5"),
    SNAPSHOT: ("#92400e", "#fef3c7"),
    SIMULATED: ("#5b21b6", "#ede9fe"),
    OFF: ("#475569", "#e2e8f0"),
}


def _src(name: str, role: str, state: str, detail: str) -> Dict[str, str]:
    return {"name": name, "role": role, "state": state, "detail": detail}


def collect(ow_live: Optional[Dict[str, Any]] = None, mandi_info: Optional[Dict[str, Any]] = None,
            river_label: str = "Simulated demo", location_source: str = "Belt preset") -> List[Dict[str, str]]:
    """Builds the list from the data the app already holds; makes no extra network calls except cached ones."""
    out: List[Dict[str, str]] = []

    # place
    src = (location_source or "").lower()
    if src.startswith("gps"):
        out.append(_src("Location", "Where your farm is", LIVE, "Your device's GPS"))
    elif src.startswith("network"):
        out.append(_src("Location", "Where your farm is", SNAPSHOT, "Approximate, from your network"))
    elif src.startswith("searched"):
        out.append(_src("Location", "Where your farm is", SNAPSHOT, "The place you searched for"))
    else:
        out.append(_src("Location", "Where your farm is", SNAPSHOT, "A regional preset, not your exact field"))

    # weather
    wx_live = bool(ow_live) and str(ow_live.get("status", "")).upper() == "LIVE"
    out.append(_src("OpenWeather", "Weather and forecast", LIVE if wx_live else SNAPSHOT,
                    "Live from OpenWeather" if wx_live else "Cached or regional values"))

    # field sensors (ANNAM.AI MCII)
    try:
        from services import annam_mcii_service as mcii
        _, fresh = mcii._get_raw_data_cached()
        state = {"LIVE": LIVE, "CACHED": SNAPSHOT}.get(fresh, OFF)
        out.append(_src("ANNAM.AI sensor stations", "Nearby field sensors", state,
                        {"LIVE": "Live from the MCII feed", "CACHED": "Last saved copy"}.get(fresh, "Not reachable")))
    except Exception:
        out.append(_src("ANNAM.AI sensor stations", "Nearby field sensors", OFF, "Not reachable"))

    # soil
    out.append(_src("Soil Health Card", "Soil nutrients and pH", SNAPSHOT, "Regional reference values, not your own soil test"))

    # prices
    if mandi_info:
        date_txt = mandi_info.get("date_latest", "")
        demo = "DEMO" in str(mandi_info.get("status", "")).upper()
        out.append(_src("Mandi prices", "What your crop sells for", SIMULATED if demo else LIVE,
                        f"Demo price file dated {date_txt}" if demo else f"Agmarknet, {date_txt}"))

    # model
    out.append(_src("Yield model", "Yield, attribution and ROI", SIMULATED, "Random Forest trained on synthetic trials"))

    # river
    if str(river_label).startswith("Simulated"):
        out.append(_src("AquaSentinel", "River water quality", SIMULATED, "Simulator; the float is not built yet"))
    else:
        out.append(_src("AquaSentinel", "River water quality", SNAPSHOT, "Readings from an uploaded device file"))

    # assistant + storage
    try:
        from services import gemini_service
        has_key = bool(gemini_service._get_gemini_key())
    except Exception:
        has_key = False
    out.append(_src("Gemini", "Plain-language answers", LIVE if has_key else OFF,
                    "Live" if has_key else "No API key set"))
    try:
        from services import supabase_client
        ok = str(supabase_client.test_supabase_connection().get("status", "")).upper() == "LIVE"
    except Exception:
        ok = False
    out.append(_src("Supabase", "Saves your season and listings", LIVE if ok else OFF,
                    "Cloud sync on" if ok else "Saving on this computer only"))
    return out


